CREATE TABLE space_posts (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    author_id bigint NOT NULL REFERENCES accounts(id),
    parent_id bigint REFERENCES space_posts(id) ON DELETE CASCADE,
    content text NOT NULL DEFAULT '' CHECK (octet_length(content) <= 4000),
    created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    CHECK (parent_id IS NULL OR parent_id <> id)
);
CREATE INDEX space_posts_by_author ON space_posts(author_id, id DESC) WHERE parent_id IS NULL;
CREATE INDEX space_posts_feed ON space_posts(id DESC) WHERE parent_id IS NULL;
CREATE INDEX space_posts_replies ON space_posts(parent_id, id) WHERE parent_id IS NOT NULL;

CREATE TABLE space_post_media (
    post_id bigint NOT NULL REFERENCES space_posts(id) ON DELETE CASCADE,
    position smallint NOT NULL CHECK (position BETWEEN 0 AND 8),
    media_id uuid NOT NULL REFERENCES media_objects(id),
    PRIMARY KEY (post_id, position),
    UNIQUE (post_id, media_id)
);
CREATE INDEX space_post_media_object ON space_post_media(media_id);

CREATE TABLE space_likes (
    post_id bigint NOT NULL REFERENCES space_posts(id) ON DELETE CASCADE,
    user_id bigint NOT NULL REFERENCES accounts(id),
    created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    PRIMARY KEY (post_id, user_id)
);

CREATE FUNCTION space_unblocked(viewer bigint, author bigint) RETURNS boolean
LANGUAGE sql STABLE STRICT AS $$
    SELECT NOT EXISTS (
        SELECT 1 FROM friend_preferences
        WHERE blocked AND ((owner_id = viewer AND other_id = author)
                        OR (owner_id = author AND other_id = viewer))
    );
$$;

CREATE FUNCTION space_can_view(viewer bigint, author bigint) RETURNS boolean
LANGUAGE sql STABLE STRICT AS $$
    SELECT viewer > 0 AND (viewer = author OR (
        EXISTS (SELECT 1 FROM friendships WHERE user_low = least(viewer, author)
                                         AND user_high = greatest(viewer, author))
        AND space_unblocked(viewer, author)
    ));
$$;

-- Replies share the root's audience, subject to the reply author's current
-- eligibility and blocks between the viewer and the reply author.
CREATE FUNCTION space_can_view_item(viewer bigint, root_author bigint, item_author bigint) RETURNS boolean
LANGUAGE sql STABLE STRICT AS $$
    SELECT space_can_view(viewer, root_author)
       AND (root_author = item_author OR (
           space_can_view(item_author, root_author) AND space_unblocked(viewer, item_author)
       ));
$$;
