CREATE TABLE reports (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reporter_id bigint REFERENCES accounts(id),
    target_kind text NOT NULL CHECK (target_kind IN ('user','group','bug')),
    target_id bigint,
    title text NOT NULL DEFAULT '',
    reason text NOT NULL CHECK (octet_length(reason) BETWEEN 1 AND 12000),
    anonymous boolean NOT NULL DEFAULT false,
    state text NOT NULL DEFAULT 'pending' CHECK (state IN ('pending','processing','resolved')),
    action_note text NOT NULL DEFAULT '',
    reviewer_id bigint REFERENCES accounts(id),
    created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    updated_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    CHECK ((target_kind='bug' AND target_id IS NULL) OR (target_kind IN ('user','group') AND target_id > 0))
);
CREATE INDEX reports_review ON reports(state,id DESC);
CREATE INDEX reports_by_reporter ON reports(reporter_id,created_at DESC);
