CREATE TABLE conversations (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind text NOT NULL CHECK (kind IN ('direct', 'group')),
    title text NOT NULL DEFAULT '',
    description text NOT NULL DEFAULT '',
    announcement text NOT NULL DEFAULT '',
    avatar_id uuid,
    owner_id bigint REFERENCES accounts(id),
    direct_low bigint REFERENCES accounts(id),
    direct_high bigint REFERENCES accounts(id),
    visibility text NOT NULL DEFAULT 'private' CHECK (visibility IN ('private','public')),
    join_policy text NOT NULL DEFAULT 'approval' CHECK (join_policy IN ('open','approval','invite')),
    invite_code text UNIQUE,
    global_mute boolean NOT NULL DEFAULT false,
    archived_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now(),
    CHECK ((kind = 'direct' AND direct_low < direct_high AND direct_low IS NOT NULL AND direct_high IS NOT NULL AND owner_id IS NULL) OR
           (kind = 'group' AND direct_low IS NULL AND direct_high IS NULL AND owner_id IS NOT NULL)),
    UNIQUE (direct_low, direct_high)
);
CREATE INDEX conversations_discover ON conversations(id) WHERE visibility='public' AND kind='group' AND archived_at IS NULL;
CREATE TABLE conversation_members (
    conversation_id bigint NOT NULL REFERENCES conversations(id),
    user_id bigint NOT NULL REFERENCES accounts(id),
    role text NOT NULL DEFAULT 'member' CHECK (role IN ('owner','admin','member')),
    title text NOT NULL DEFAULT '',
    joined_at timestamptz NOT NULL DEFAULT now(),
    muted_until timestamptz,
    hidden boolean NOT NULL DEFAULT false,
    read_seq bigint NOT NULL DEFAULT 0 CHECK (read_seq >= 0),
    PRIMARY KEY (conversation_id,user_id)
);
CREATE INDEX conversation_members_user ON conversation_members(user_id,conversation_id);
CREATE TABLE conversation_heads (
    conversation_id bigint PRIMARY KEY REFERENCES conversations(id),
    head bigint NOT NULL DEFAULT 0 CHECK (head >= 0),
    last_sent_at timestamptz NOT NULL DEFAULT now()
);
