CREATE TABLE friendships (
    user_low bigint NOT NULL REFERENCES accounts(id),
    user_high bigint NOT NULL REFERENCES accounts(id),
    created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    PRIMARY KEY (user_low, user_high),
    CHECK (user_low < user_high)
);
CREATE INDEX friendships_user_high ON friendships(user_high, user_low);

CREATE TABLE friend_preferences (
    owner_id bigint NOT NULL REFERENCES accounts(id),
    other_id bigint NOT NULL REFERENCES accounts(id),
    blocked boolean NOT NULL DEFAULT false,
    remark text NOT NULL DEFAULT '' CHECK (char_length(remark) <= 64),
    PRIMARY KEY (owner_id, other_id),
    CHECK (owner_id <> other_id)
);

CREATE TABLE friend_requests (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sender_id bigint NOT NULL REFERENCES accounts(id),
    recipient_id bigint NOT NULL REFERENCES accounts(id),
    message text NOT NULL DEFAULT '' CHECK (char_length(message) <= 500),
    status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','accepted','rejected','cancelled')),
    created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    resolved_at timestamptz,
    CHECK (sender_id <> recipient_id),
    CHECK ((status = 'pending') = (resolved_at IS NULL))
);
CREATE UNIQUE INDEX friend_requests_pending_pair
    ON friend_requests(LEAST(sender_id, recipient_id), GREATEST(sender_id, recipient_id)) WHERE status = 'pending';
CREATE INDEX friend_requests_inbox ON friend_requests(recipient_id, status, id DESC);
CREATE INDEX friend_requests_outbox ON friend_requests(sender_id, status, id DESC);
CREATE INDEX friend_requests_recent ON friend_requests(sender_id, created_at);

ALTER TABLE conversations
    DROP CONSTRAINT conversations_join_policy_check,
    ADD CHECK (join_policy IN ('open','code','approval','invite')),
    ADD COLUMN discoverable boolean NOT NULL DEFAULT true,
    ADD COLUMN allow_invite boolean NOT NULL DEFAULT true,
    ADD COLUMN code_single_use boolean NOT NULL DEFAULT true,
    ADD COLUMN join_question text NOT NULL DEFAULT '' CHECK (char_length(join_question) <= 200);
ALTER TABLE conversation_members
    ADD COLUMN level smallint NOT NULL DEFAULT 1 CHECK (level BETWEEN 1 AND 100);
CREATE UNIQUE INDEX conversation_members_single_owner ON conversation_members(conversation_id) WHERE role = 'owner';

CREATE TABLE group_join_requests (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id bigint NOT NULL REFERENCES conversations(id),
    user_id bigint NOT NULL REFERENCES accounts(id),
    inviter_id bigint REFERENCES accounts(id),
    kind text NOT NULL CHECK (kind IN ('application','invitation')),
    answer text NOT NULL DEFAULT '' CHECK (char_length(answer) <= 500),
    status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','accepted','rejected','cancelled')),
    created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    resolved_at timestamptz,
    CHECK ((kind = 'invitation') = (inviter_id IS NOT NULL)),
    CHECK (inviter_id <> user_id),
    CHECK ((status = 'pending') = (resolved_at IS NULL))
);
CREATE UNIQUE INDEX group_join_requests_pending ON group_join_requests(conversation_id, user_id, kind) WHERE status = 'pending';
CREATE INDEX group_join_requests_review ON group_join_requests(conversation_id, kind, status, id DESC);
CREATE INDEX group_join_requests_inbox ON group_join_requests(user_id, kind, status, id DESC);

CREATE TABLE group_transfers (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id bigint NOT NULL REFERENCES conversations(id),
    from_user_id bigint NOT NULL REFERENCES accounts(id),
    to_user_id bigint NOT NULL REFERENCES accounts(id),
    status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','accepted','rejected','cancelled')),
    created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    resolved_at timestamptz,
    CHECK (from_user_id <> to_user_id),
    CHECK ((status = 'pending') = (resolved_at IS NULL))
);
CREATE UNIQUE INDEX group_transfers_one_pending ON group_transfers(conversation_id) WHERE status = 'pending';
CREATE INDEX group_transfers_cooldown ON group_transfers(conversation_id, resolved_at DESC) WHERE status = 'accepted';
CREATE INDEX group_transfers_inbox ON group_transfers(to_user_id, status, id DESC);
CREATE INDEX group_transfers_outbox ON group_transfers(from_user_id, status, id DESC);

CREATE TABLE notifications (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES accounts(id),
    kind text NOT NULL,
    data jsonb NOT NULL DEFAULT '{}'::jsonb,
    created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    read_at timestamptz
);
CREATE INDEX notifications_inbox ON notifications(user_id, id DESC);
CREATE INDEX notifications_unread ON notifications(user_id, id DESC) WHERE read_at IS NULL;
