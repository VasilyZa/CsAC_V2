CREATE TABLE media_objects (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    owner_id bigint NOT NULL REFERENCES accounts(id),
    state text NOT NULL DEFAULT 'pending' CHECK (state IN ('pending', 'ready')),
    purpose text NOT NULL CHECK (purpose IN ('avatar', 'message', 'group', 'space')),
    mime text NOT NULL CHECK (length(mime) BETWEEN 1 AND 127),
    filename text NOT NULL CHECK (octet_length(filename) BETWEEN 1 AND 255),
    size bigint NOT NULL CHECK (size > 0),
    stored_key text GENERATED ALWAYS AS
        ('objects/' || substr(id::text, 1, 2) || '/' || substr(id::text, 3, 2) || '/' || id::text) STORED,
    created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    ready_at timestamptz,
    expires_at timestamptz,
    purged_at timestamptz,
    CHECK ((state = 'pending' AND ready_at IS NULL AND expires_at IS NOT NULL AND purged_at IS NULL)
        OR (state = 'ready' AND ready_at IS NOT NULL)),
    CHECK (purged_at IS NULL OR expires_at IS NOT NULL)
);
CREATE INDEX media_objects_expiry ON media_objects(expires_at, id)
    WHERE expires_at IS NOT NULL AND purged_at IS NULL;
CREATE INDEX media_objects_unreferenced_candidates ON media_objects(ready_at, id)
    WHERE state = 'ready' AND expires_at IS NULL;

ALTER TABLE conversations ADD CONSTRAINT conversations_avatar_media
    FOREIGN KEY (avatar_id) REFERENCES media_objects(id);
CREATE INDEX conversations_avatar_media_idx ON conversations(avatar_id) WHERE avatar_id IS NOT NULL;

CREATE TABLE group_file_folders (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id bigint NOT NULL REFERENCES conversations(id),
    name text NOT NULL CHECK (length(name) BETWEEN 1 AND 50 AND name = btrim(name)),
    created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    UNIQUE (conversation_id, id),
    UNIQUE (conversation_id, name)
);

CREATE TABLE group_files (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id bigint NOT NULL REFERENCES conversations(id),
    media_id uuid NOT NULL REFERENCES media_objects(id),
    uploader_id bigint NOT NULL REFERENCES accounts(id),
    folder_id bigint,
    created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    UNIQUE (conversation_id, media_id),
    FOREIGN KEY (conversation_id, folder_id)
        REFERENCES group_file_folders(conversation_id, id) ON DELETE SET NULL (folder_id)
);
CREATE INDEX group_files_list ON group_files(conversation_id, id DESC);
CREATE INDEX group_files_folder_list ON group_files(conversation_id, folder_id, id DESC);
CREATE INDEX group_files_media ON group_files(media_id);
