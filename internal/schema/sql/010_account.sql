CREATE TABLE accounts (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username text NOT NULL,
    nickname text NOT NULL,
    password_hash text NOT NULL DEFAULT '',
    email text,
    email_verified boolean NOT NULL DEFAULT false,
    registration_grant boolean NOT NULL DEFAULT false,
    site_admin boolean NOT NULL DEFAULT false,
    status text NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'banned', 'deleted')),
    avatar_id uuid,
    bio text NOT NULL DEFAULT '',
    allow_auto_join boolean NOT NULL DEFAULT true,
    pat_action text NOT NULL DEFAULT '拍了拍',
    is_first_login boolean NOT NULL DEFAULT true,
    ban_until timestamptz,
    ban_reason text NOT NULL DEFAULT '',
    deleted_at timestamptz,
    purged_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT clock_timestamp()
);
CREATE UNIQUE INDEX accounts_username_folded ON accounts(lower(username COLLATE "C"));
CREATE UNIQUE INDEX accounts_email_folded ON accounts(lower(email COLLATE "C")) WHERE email IS NOT NULL;
CREATE INDEX accounts_avatar ON accounts(avatar_id) WHERE avatar_id IS NOT NULL;
CREATE INDEX accounts_ban_expiration ON accounts(ban_until) WHERE status = 'banned' AND ban_until IS NOT NULL;
CREATE INDEX accounts_deletion_expiration ON accounts(deleted_at) WHERE status = 'deleted' AND purged_at IS NULL;

CREATE TABLE account_sessions (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id bigint NOT NULL REFERENCES accounts(id),
    token_hash bytea NOT NULL UNIQUE CHECK (octet_length(token_hash) = 32),
    created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    expires_at timestamptz NOT NULL
);
CREATE INDEX account_sessions_user ON account_sessions(user_id, created_at DESC, id DESC);
CREATE INDEX account_sessions_expiration ON account_sessions(expires_at);

CREATE TABLE account_email_challenges (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    purpose text NOT NULL CHECK (purpose IN ('signup', 'signin', 'bind', 'restore')),
    subject_id bigint REFERENCES accounts(id),
    email_key bytea NOT NULL CHECK (octet_length(email_key) = 32),
    origin_key bytea NOT NULL CHECK (octet_length(origin_key) = 32),
    secret_hash bytea NOT NULL CHECK (octet_length(secret_hash) = 32),
    nonce bytea NOT NULL CHECK (octet_length(nonce) = 16),
    attempts integer NOT NULL DEFAULT 0 CHECK (attempts BETWEEN 0 AND 5),
    used_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    expires_at timestamptz NOT NULL
);
CREATE INDEX account_email_challenges_mailbox ON account_email_challenges(purpose, email_key, created_at DESC, id DESC);
CREATE INDEX account_email_challenges_origin ON account_email_challenges(purpose, origin_key, created_at DESC);
CREATE INDEX account_email_challenges_subject ON account_email_challenges(subject_id) WHERE used_at IS NULL;
CREATE INDEX account_email_challenges_expiration ON account_email_challenges(expires_at);

CREATE TABLE account_registration_codes (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code_hash bytea NOT NULL UNIQUE CHECK (octet_length(code_hash) = 32),
    code_ciphertext bytea NOT NULL,
    max_uses integer NOT NULL CHECK (max_uses > 0),
    used_count integer NOT NULL DEFAULT 0 CHECK (used_count BETWEEN 0 AND max_uses),
    created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    created_by bigint NOT NULL REFERENCES accounts(id),
    expires_at timestamptz,
    revoked_at timestamptz,
    revoked_by bigint REFERENCES accounts(id),
    CHECK ((revoked_at IS NULL) = (revoked_by IS NULL))
);
CREATE TABLE account_registration_redemptions (
    user_id bigint PRIMARY KEY REFERENCES accounts(id),
    code_id bigint NOT NULL REFERENCES account_registration_codes(id),
    registered_at timestamptz NOT NULL DEFAULT clock_timestamp()
);
CREATE INDEX account_registration_redemptions_code ON account_registration_redemptions(code_id, user_id DESC);
